import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { distanceAtLine, engraving, layerChange, locate, parseGcode, pulse, rapid, travel } from '../src/shared/gcode'
import { loadGcodeFile } from '../src/shared/gcodeFile'

describe('LDS toolpaths', () => {
  it('recognizes standalone feed setup only for an LDS slide export', () => {
    const header = ';gc={"process":"slide"}'
    const path = parseGcode([header, 'G101 F30', 'G90', 'G0X1Y2', 'G1X3Y4'].join('\n'))
    expect(path.issue).toBeNull()
    expect(path.skipped).toEqual({ count: 1, firstLine: 2, codes: [101] })
    expect(path.diagnostics).toEqual([{ reason: 'G101 设置滑台连续进给。轨迹按程序坐标显示。', count: 1, firstLine: 2 }])
    expect([...path.lines]).toEqual([4, 5])
    expect(path.end).toEqual([3, 4, 0])
    expect(parseGcode('G101 F30\nG0X1').ignored?.examples[0].line).toBe(1)
    for (const block of ['G101 F30 X1', 'G101 F0', 'G101 G90 F30']) {
      expect(parseGcode([header, block].join('\n')).ignored?.examples[0].line).toBe(2)
    }
  })

  it.skipIf(!process.env.LDS_SLIDE_SAMPLE)('loads the supplied slide file through the file parser', async () => {
    const file = new Blob([readFileSync(process.env.LDS_SLIDE_SAMPLE!, 'utf8')])
    const { path } = await loadGcodeFile(file)
    expect(path.issue).toBeNull()
    expect(path.skipped).toEqual({ count: 1, firstLine: 2, codes: [101] })
    expect(path.end).toEqual([14.82, 68.327, 0])
  })

  it('ignores controller payloads and hash comments while preserving source line numbers', () => {
    const path = parseGcode('G91\nG1X2\n  :G90 G92X99\n # G25X80\nG1X3')
    expect(path.issue).toBeNull()
    expect(path.pointMode).toBe(false)
    expect([...path.lines]).toEqual([2, 5])
    expect(path.end).toEqual([5, 0, 0])
  })

  it('previews each LDS cuteng repeat block once and still validates unsupported loops', () => {
    const source = '# Generated by cuteng (line-cut enhancement)\nG0Z0.06\nM98 L100\nG1X2\nM99\nG1X3'
    const path = parseGcode(source)
    expect(path.issue).toBeNull()
    expect(path.previewedLoops).toBe(1)
    expect([...path.lines]).toEqual([2, 4, 6])
    expect(path.end).toEqual([3, 0, 0.06])
    expect(parseGcode(source.replace('M99\n', '')).ignored?.examples[0].line).toBe(3)
    expect(parseGcode('M98 L100\nG1X2\nM99').ignored?.examples[0].line).toBe(1)
  })

  it.skipIf(!process.env.LDS_CUTENG_SAMPLE)('loads the supplied cuteng export to the final Z move', () => {
    const path = parseGcode(readFileSync(process.env.LDS_CUTENG_SAMPLE!, 'utf8'))
    expect(path.issue).toBeNull()
    expect(path.previewedLoops).toBe(10)
    expect(path.lines.at(-1)).toBe(26709)
    expect(path.end[2]).toBeCloseTo(0)
  })

  it('plots discrete crystal pulses and restores optical Z layers', () => {
    const path = parseGcode([
      ';gc={"offset":{"z":23.728},"process":"crystal","refractiveRate":1.517}',
      'G90', 'G21', 'G0 Q40 T0.27',
      'G91', 'G0Z-0.011F1', 'G90',
      'G25X42.157Y19.237F3000S500', 'G25X42.157Y19.237',
      'G91', 'G0Z-0.029F1', 'G90', 'G25X42.156Y19.258', 'M2',
    ].join('\n'))
    expect(path.issue).toBeNull()
    expect(path.crystal).toBe(true)
    expect([...path.kinds]).toEqual([layerChange, pulse, pulse, layerChange, pulse])
    expect([...path.powers]).toEqual([0, 500, 500, 0, 500])
    expect(path.bounds?.min).toEqual([42.156, 19.237, 23.728 + 0.011 * 1.517])
    expect(path.end[2]).toBeCloseTo(23.728 + 0.04 * 1.517, 8)
    expect(locate(path, distanceAtLine(path, 8))?.position[0]).toBeCloseTo(42.157, 4)
    expect(distanceAtLine(path, 9)).toBeGreaterThan(distanceAtLine(path, 8))
  })

  it('maps absolute crystal focus and keeps unrelated motion dialects guarded', () => {
    const path = parseGcode([
      ';gc={"process":"crystal","refractiveRate":1.517}',
      'G0 Z184.520 T0.27', 'G25X30Y20',
      'G0 Z170.962', 'G25X30Y20',
    ].join('\n'))
    expect(path.issue).toBeNull()
    expect(path.bounds?.min[2]).toBe(0)
    expect(path.end[2]).toBeCloseTo((184.520 - 170.962) * 1.517, 8)
    expect(parseGcode('G0 T1').ignored?.examples[0].line).toBe(1)
    expect(parseGcode('G92 X30 Y20').ignored?.examples[0].line).toBe(1)
  })

  it('loads headerless G25 points with absolute Z, skips bare wrappers and preserves modal power', () => {
    const path = parseGcode('G90\nG25 S500 T27\nG102\nG0Z40.402\nG103\nG25X3Y4\nG25X5Y6S200\nG25X7Y8')
    expect(path.issue).toBeNull()
    expect(path.pointMode).toBe(true)
    expect(path.crystal).toBe(false)
    expect(path.skipped).toEqual({ count: 2, firstLine: 3, codes: [102, 103] })
    expect([...path.kinds]).toEqual([layerChange, pulse, pulse, pulse])
    expect([...path.powers]).toEqual([0, 500, 200, 200])
    expect(path.bounds?.min).toEqual([3, 4, 40.402])
    expect(path.end).toEqual([7, 8, 40.402])
    expect(parseGcode('G25X1\nG102X2\nG25X3').ignored?.examples[0].line).toBe(2)
    expect(parseGcode('G25X1\nG92X2\nG25X3').ignored?.examples[0].line).toBe(2)
  })

  it('accepts LDS laser frequency in setup and compact motion blocks', () => {
    const path = parseGcode(`G90
G21
M4 S800
;blockConfig={"mode":"normal","type":"line"}
G0 F3000 Q40 S800
G0X24.03Y12.9
G1X40.8Y12.9F3000S800Q40
G1X40.8Y26.97
G1X24.03Y26.97
G1X24.03Y12.9
M5
M2`)
    expect(path.issue).toBeNull()
    expect([...path.lines]).toEqual([6, 7, 8, 9, 10])
    expect([...path.kinds]).toEqual([rapid, engraving, engraving, engraving, engraving])
    expect([...path.powers]).toEqual([0, 800, 800, 800, 800])
    expect(path.end).toEqual([24.03, 12.9, 0])
  })

  it('separates powered moves, raster returns and M8 accessory power', () => {
    const path = parseGcode(`G90G21
M4S600
G0X10
G1X20
M8 S25
Y1
G1X10S0
M9
M400
X20S300
M5
X21
M2
G0X99`)
    expect(path.issue).toBeNull()
    expect([...path.kinds]).toEqual([rapid, engraving, engraving, travel, engraving, travel])
    expect([...path.powers]).toEqual([0, 600, 600, 0, 300, 0])
    expect(path.end).toEqual([21, 1, 0])
    expect(locate(path, 15)).toEqual({ index: 1, line: 4, position: [15, 0, 0] })
    expect(locate(path, Infinity)?.position).toEqual(path.end)
  })

  it('handles imperial coordinates, relative Z and arcs with source-line mapping', () => {
    const path = parseGcode('G20G90G0X1\rG21G91G1Z2\r\nG90G2X45.4Y0I10\nG3X25.4Y0R10')
    expect(path.issue).toBeNull()
    expect(path.end).toEqual([25.4, 0, 2])
    expect(path.bounds?.max[2]).toBe(2)
    expect(path.bounds?.max[1]).toBeCloseTo(10, 1)
    expect(path.distances.at(-1)).toBeCloseTo(27.4 + Math.PI * 20, 0)
    expect([...new Set(path.lines)]).toEqual([1, 2, 3, 4])
  })

  it('skips entire invalid blocks and retains the last valid modal state', () => {
    const path = parseGcode('G91\nM4 S80\nG1X1\nG90 G20 G92X0\nG2X2R0.1 M5 S0\nX4')
    expect(path.issue).toBeNull()
    expect(path.ignored).toEqual({ count: 2, examples: [
      { line: 4, message: '不支持指令 G92。' },
      { line: 5, message: '圆弧半径与端点不匹配。' },
    ] })
    expect(path.end).toEqual([5, 0, 0])
    expect([...path.lines]).toEqual([3, 6])
    expect([...path.powers]).toEqual([80, 80])
    expect(parseGcode('G0X1\nG2X2R0.1').ignored?.examples[0].line).toBe(2)
  })

  it('ignores curveeng comments and identifies curved coordinates from the LDS header', () => {
    const body = 'G0X1\n# Generated by curveeng\nG1Z2'
    const plain = parseGcode(body)
    expect(plain.curved).toBe(false)
    expect(plain.diagnostics).toEqual([])
    for (const header of [';gc={"process":"curved"}', ';gc={"curveBedFromSurface":true}']) {
      const path = parseGcode(header + '\n' + body)
      expect(path.curved).toBe(true)
      expect(path.diagnostics).toEqual([])
      expect([...path.lines]).toEqual([2, 4])
    }
  })

  it.skipIf(!process.env.LDS_CURVED_SAMPLE)('loads the supplied curved file with no skipped rows', async () => {
    const file = new Blob([readFileSync(process.env.LDS_CURVED_SAMPLE!, 'utf8')])
    const { path } = await loadGcodeFile(file)
    expect(path.curved).toBe(true)
    expect(path.issue).toBeNull()
    expect(path.diagnostics).toEqual([])
    expect(path.lines.length).toBeGreaterThan(200_000)
  })

  it('counts repeated diagnostics and keeps one line for a shared reason', () => {
    const path = parseGcode('G92X0\n'.repeat(25) + 'G25X1\nG102\nG103\nG102\nG2X2R0.1')
    expect(path.diagnostics).toEqual([
      { reason: '不支持指令 G92。', count: 25, firstLine: 1 },
      { reason: 'G102 / G103 是 LDS 点加工控制指令，已从轨迹预览中跳过。', count: 3, firstLine: 27 },
      { reason: '圆弧半径与端点不匹配。', count: 1, firstLine: 30 },
    ])
  })

  it('seeks to the end of a motion line and holds the position on non-motion lines', () => {
    const path = parseGcode('; start\nG0X10\nG3X20I5\n; hold\nG1Y5\nM2')
    expect(path.issue).toBeNull()
    expect(locate(path, distanceAtLine(path, 1))?.position).toEqual([0, 0, 0])
    expect(distanceAtLine(path, 2)).toBe(10)
    const endOfArc = distanceAtLine(path, 3)
    expect(locate(path, endOfArc)?.position).toEqual([20, 0, 0])
    expect(distanceAtLine(path, 4)).toBe(endOfArc)
    expect(distanceAtLine(path, 6)).toBe(path.distances.at(-1))
  })

  const fixtures = process.env.LDS_FIXTURE_ROOT
  it.skipIf(!fixtures)('matches the LDS image and MD2 line samples', () => {
    const load = (path: string) => parseGcode(readFileSync(join(fixtures!, path), 'utf8'))
    const image = load('input/image/t010_img_01.gcode')
    expect(image.issue).toBeNull()
    expect(image.bounds?.max).toEqual([50, 70, 0])
    expect(image.end).toEqual([10, 20, 0])
    expect([...image.powers].filter(Boolean)).toEqual([500, 500, 500, 500])

    const line = load('md2-handoff/_repeat-compare/v-mt-01-line-repeat-1.gcode')
    expect(line.issue).toBeNull()
    expect(line.end).toEqual([133.9, 85.66, 10])
    expect(line.bounds?.max[2]).toBe(21.8)
    expect(line.powers[Array.from(line.lines).indexOf(13)]).toBe(200)
  })
})
